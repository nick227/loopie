// Calendar idea-template content — see schema.prisma's GoalIdeaTemplate doc comment. Plain
// content, not UI: the frontend never hard-codes a suggestion string, it only ever renders
// whatever CalendarService resolves from these rows (system templates) or a business's own
// GoalIdeaTemplate rows (user-typed ideas). Same "content model separate from rendering" split as
// packages/db/src/systemTemplates.ts's landing-page templates.
//
// "Never run out of useful ideas, never feel buried in a checklist" (2026-09-02 reserve-library
// pass): this file is the reserve — deliberately much larger than the ~18 ideas CalendarService
// ever shows at once (MAX_IDEAS). What keeps 40+ templates from feeling like a checklist is the
// combination of rules in lib/coachRules.ts, not content curation at read time:
//   - prerequisites (requiresTemplateIds) hide later-journey ideas until earlier ones are real
//   - dynamic eligibility (metricKey) only offers an idea while its condition genuinely holds
//   - repeatable + cooldownDays lets a genuinely recurring idea ("ask for reviews") come back
//     after a real gap, while a one-time setup task (the default) disappears for good once done
//   - stage + category diversification (CalendarService.selectDiverse) keeps the visible slice
//     spread across Foundation..Grow and across Pages/Ads/CRM/Messaging/River, not clustered
//
// Every `detail` is exactly one plain sentence: what this is worth doing, not what it does (the
// title already says what). No AI-generated content yet — this is the deterministic base the
// product spec asked for before any of that.
//
// Two kinds live here:
//   - STATIC_GOAL_IDEA_TEMPLATES: no live condition — always offered once businessTypes/
//     prerequisites/cooldown allow it.
//   - DYNAMIC_GOAL_IDEA_TEMPLATES: also carry a `metricKey` lib/coachRules.ts evaluates against
//     real product state to decide whether to surface it at all right now.
//
// `stage` places each idea on the one universal progression (schema.prisma's CoachStage doc
// comment): Foundation -> Attract -> Capture -> Convert -> Grow.
export type GoalIdeaTemplateSeed = {
  id: string
  title: string
  detail: string
  ideaType:
    'ACTION' | 'OUTCOME' | 'MAINTENANCE' | 'CREATION' | 'RELATIONSHIP' | 'EXPERIMENT' | 'REVIEW'
  subjectType: 'GENERAL' | 'CRM' | 'ADVERTISEMENT' | 'PAGE' | 'RIVER' | 'BUSINESS'
  stage: 'FOUNDATION' | 'ATTRACT' | 'CAPTURE' | 'CONVERT' | 'GROW'
  requiresTemplateIds: string[] | null
  // The in-app destination this idea's action button opens — Calendar as command center, not
  // just a list. Null for ideas with no single obvious page. A couple of dynamic templates
  // (publish-homepage, finish-ad-draft) override this with a live-resolved target in
  // lib/coachRules.ts instead of using this static one.
  action: { target: string; label: string } | null
  businessTypes: string[] | null
  defaultHorizon: 'TODAY' | 'THIS_WEEK' | 'NEXT_WEEK'
  defaultEstimateMinutes: number | null
  trackingType: 'MANUAL' | 'ENTITY_STATE' | 'COUNT'
  metricKey: string | null
  targetValue: number | null
  priorityWeight: number
  // Only ever consulted for a static template (metricKey null) — see
  // schema.prisma's GoalIdeaTemplate.repeatable doc comment. false (the default posture here,
  // set explicitly on every entry for clarity) means one-time: done once, gone for good.
  repeatable: boolean
  cooldownDays: number | null
}

